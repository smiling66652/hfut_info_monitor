def classify_hfut(title: str, score: int = 0) -> str:
    """按优先级匹配分类，若无匹配但 score>=10 则归类为"重要"。

    Args:
        title: 通知标题
        score: 相关度分值

    Returns:
        分类名称（"保研"/"竞赛"/.../"重要"/""）
    """
    for cat in PRIORITY_ORDER:
        for kw in KEYWORDS[cat]:
            if kw in title:
                return cat
    if score >= 10:
        return "重要"
    return ""
